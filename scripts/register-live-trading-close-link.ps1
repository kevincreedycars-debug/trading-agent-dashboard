# Registers the live dashboard's own close link on this PC: the one-click route from the Open positions
# table's Close button to the trading loop's hand-close.
#
#   powershell -NoProfile -ExecutionPolicy Bypass -File scripts/register-live-trading-close-link.ps1
#   powershell -NoProfile -ExecutionPolicy Bypass -File scripts/register-live-trading-close-link.ps1 -Unregister
#
# What it registers, and what it deliberately does not:
#
#   * a per-user URL protocol, `HKCU\Software\Classes\l2lclose`, whose only action is to run
#     tools/live-trading-close-link/open-live-trading-close-link.ps1 with the URL. The page can therefore hand
#     over one ticket number and nothing else;
#   * one generated runner, tmp/live-trading-close-run.cmd, holding this machine's own paths (node, python,
#     the terminal folder, the state, log, lock and journal). It is generated here rather than committed,
#     because those paths belong to this machine;
#   * no scheduled task, no service and no listening port: the handler runs only when a link is pressed, and
#     the loop it calls is the same one the five-minute task runs.
param(
  [string]$RepoRoot = "",
  [string]$Node = "",
  [string]$Python = "",
  [string]$Terminal = "C:\Program Files\FTMO Global Markets MT5 Terminal",
  [switch]$Unregister
)

$ErrorActionPreference = "Stop"
if (-not $RepoRoot) { $RepoRoot = Split-Path -Parent $PSScriptRoot }
$RepoRoot = (Resolve-Path -LiteralPath $RepoRoot).Path

$protocolKey = "HKCU:\Software\Classes\l2lclose"
$runnerPath = Join-Path $RepoRoot "tmp\live-trading-close-run.cmd"
$handlerPath = Join-Path $RepoRoot "tools\live-trading-close-link\open-live-trading-close-link.ps1"

if ($Unregister) {
  if (Test-Path -LiteralPath $protocolKey) { Remove-Item -LiteralPath $protocolKey -Recurse -Force }
  if (Test-Path -LiteralPath $runnerPath) { Remove-Item -LiteralPath $runnerPath -Force }
  Write-Output "Unregistered the l2lclose link and removed $runnerPath."
  exit 0
}

if (-not (Test-Path -LiteralPath $handlerPath)) { throw "The handler is missing: $handlerPath" }
if (-not $Node) {
  $resolved = Get-Command node -ErrorAction SilentlyContinue
  if (-not $resolved) { throw "node is not on PATH; pass -Node <path>." }
  $Node = $resolved.Source
}
if (-not $Python) {
  $resolved = Get-Command python -ErrorAction SilentlyContinue
  if (-not $resolved) { throw "python is not on PATH; pass -Python <path>." }
  $Python = $resolved.Source
}
# The terminal folder is written into the runner only when it is there: with it absent the order tool's own
# discovery is used, exactly as the trader task's runner treats it.
$terminalArgument = ""
if ($Terminal -and (Test-Path -LiteralPath $Terminal)) {
  $terminalArgument = " --terminal `"$Terminal`""
} else {
  Write-Output "Terminal path '$Terminal' is absent; the order tool's own discovery will be used."
}

$traderScript = Join-Path $RepoRoot "scripts\run-live-trading-trader.js"
if (-not (Test-Path -LiteralPath $traderScript)) { throw "The loop is missing: $traderScript" }

# The runner is a plain command line and no quotes of its own beyond the paths, the way the trader task's
# runner is written: the close link adds one argument - the ticket - and nothing else. No --align, because a
# hand close is not a cadence and must not wait for the next bar close.
$lines = @(
  "@echo off"
  "rem Generated by scripts/register-live-trading-close-link.ps1. Machine specific; rewritten at each registration."
  "rem Argument 1 is the ticket the close link carried. Nothing else is ever passed to the loop."
  "cd /d `"$RepoRoot`""
  "`"$Node`" `"$traderScript`" --once --close-ticket %1 --confirm-live --python `"$Python`" --state `"$RepoRoot\tmp\live-trading-trader-state.json`" --log `"$RepoRoot\tmp\live-trading-trader.log`" --lock `"$RepoRoot\tmp\live-trading-trader.lock`" --journal `"$RepoRoot\tmp\live-trading-orders.log`"$terminalArgument"
  "exit /b %ERRORLEVEL%"
)
New-Item -ItemType Directory -Force -Path (Split-Path -Parent $runnerPath) | Out-Null
Set-Content -LiteralPath $runnerPath -Value ($lines -join "`r`n") -Encoding ASCII

# The registered command, in one piece so a reader can see exactly what a press of the link runs.
$command = "powershell.exe -NoProfile -ExecutionPolicy Bypass -WindowStyle Hidden -File `"$handlerPath`" -Url `"%1`" -Runner `"$runnerPath`""
New-Item -Path $protocolKey -Force | Out-Null
New-ItemProperty -Path $protocolKey -Name "(Default)" -Value "URL:L2L live trading close link" -PropertyType String -Force | Out-Null
New-ItemProperty -Path $protocolKey -Name "URL Protocol" -Value "" -PropertyType String -Force | Out-Null
New-Item -Path (Join-Path $protocolKey "shell\open\command") -Force | Out-Null
New-ItemProperty -Path (Join-Path $protocolKey "shell\open\command") -Name "(Default)" -Value $command -PropertyType String -Force | Out-Null

Write-Output "Registered l2lclose:"
Write-Output "  command: $command"
Write-Output "  runner:  $runnerPath"
Write-Output "A press of the dashboard's Close now link will ask for confirmation and then run the loop's own hand-close."
