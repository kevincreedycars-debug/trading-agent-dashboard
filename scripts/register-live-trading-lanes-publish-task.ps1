<#
.SYNOPSIS
  Registers (or removes) the one Windows scheduled task that publishes every Live Trading lane, in one commit.

.DESCRIPTION
  Both FTMO accounts run their own feed cadence in their own checkout, and each writes its own snapshot. This
  script puts the one step that writes to production on a ten-minute clock: scripts/publish-live-trading-lanes.js
  reads every lane's artifact, refuses the run if one of them is missing, unreadable, stale or not the account
  the lanes file says it is, and hands the whole set to scripts/publish-live-trading-feed.js as a single commit
  and a single Pages build.

  One publisher, not one per lane, is the point. Two publishers a few seconds apart would serve a page whose
  account #1 block and account #2 block come from different reads, and two runs racing the same branch is where
  a rejected push comes from. Ten minutes is also the publisher's own default interval, six builds an hour
  against GitHub's documented soft limit of ten.

  The task runs as the account that can push: the publish checkout
  (<canonical root>/.local/live-trading-feed-publish by default) must already be authenticated for this user.
  Nothing here reads a password, a token or a broker credential; the lanes file carries labels and paths only.

.EXAMPLE
  powershell -NoProfile -ExecutionPolicy Bypass -File scripts/register-live-trading-lanes-publish-task.ps1 -Show
  powershell -NoProfile -ExecutionPolicy Bypass -File scripts/register-live-trading-lanes-publish-task.ps1
  powershell -NoProfile -ExecutionPolicy Bypass -File scripts/register-live-trading-lanes-publish-task.ps1 -Test
  powershell -NoProfile -ExecutionPolicy Bypass -File scripts/register-live-trading-lanes-publish-task.ps1 -Remove
#>
param(
  [string] $TaskName = "LiveTradingPublishLanes019",
  [int] $IntervalMinutes = 10,
  [string] $RepoRoot = (Split-Path -Parent $PSScriptRoot),
  [string] $Config = "config/live-trading-lanes.json",
  [string] $Checkout = "",
  [int] $MinIntervalSeconds = 600,
  [string] $Node = $null,
  [string] $HiddenRunner = "C:\Users\A17\.trading-agent-dashboard\scripts\run-hidden.vbs",
  [switch] $NoStart,
  [switch] $Remove,
  [switch] $Show,
  [switch] $Test
)

$ErrorActionPreference = "Stop"

if ($Remove) {
  foreach ($name in @($TaskName, "$TaskName-SelfTest")) {
    $existing = Get-ScheduledTask -TaskName $name -ErrorAction SilentlyContinue
    if (-not $existing) { continue }
    if ($existing.State -eq "Running") { Stop-ScheduledTask -TaskName $name }
    Unregister-ScheduledTask -TaskName $name -Confirm:$false
    Write-Output "Removed scheduled task $name. What it already pushed stays on the branch."
  }
  return
}

$runner = Join-Path $RepoRoot "scripts\publish-live-trading-lanes.js"
$configPath = Join-Path $RepoRoot $Config
foreach ($required in @($runner, $configPath)) {
  if (-not (Test-Path -LiteralPath $required)) { throw "Not found: $required" }
}

if (-not $Node) {
  $resolved = Get-Command node -ErrorAction SilentlyContinue
  if (-not $resolved) { throw "node is not on PATH; pass -Node <path>." }
  $Node = $resolved.Source
}

$wrapperPath = Join-Path $RepoRoot "tmp\live-trading-lanes-publish-run.cmd"
$statePath = Join-Path $RepoRoot "tmp\live-trading-publish-state.json"
$checkoutArgument = ""
if ($Checkout) { $checkoutArgument = " --checkout `"$Checkout`"" }

# The hidden launcher takes the command to run as one argument, and Task Scheduler doubles every quote inside an
# argument it stores, so the command the task passes is quote-free - `cmd.exe /c <wrapper>` - and every quote lives
# inside the wrapper, where cmd.exe's own rules apply.
function Write-Wrapper($path, $lines) {
  $directory = Split-Path -Parent $path
  New-Item -ItemType Directory -Force -Path $directory | Out-Null
  Set-Content -LiteralPath $path -Value $lines -Encoding ascii
  return $path
}

$logPath = Join-Path $RepoRoot "tmp\live-trading-lanes-publish.log"

# One place the command is spelled out, so the registered task and the self test cannot drift apart. A scheduled
# task has no console, so the self test gets the same command with its own output redirected to a file.
function Get-WrapperLines($extraFlags, $redirect) {
  $command = "`"$Node`" `"$runner`" --config `"$configPath`" --min-interval-seconds $MinIntervalSeconds" +
    "$checkoutArgument $extraFlags --json"
  if ($redirect) { $command = "$command > `"$redirect`" 2>&1" }
  return @(
    "@echo off",
    "rem Generated by scripts/register-live-trading-lanes-publish-task.ps1. Machine specific; rewritten at each registration.",
    "rem The quotes belong here on purpose: the command line the task passes must not contain any.",
    "cd /d `"$RepoRoot`"",
    $command,
    "exit /b %ERRORLEVEL%"
  )
}

Write-Wrapper $wrapperPath (Get-WrapperLines "" "") | Out-Null

if ($wrapperPath -match " ") {
  throw "The wrapper path '$wrapperPath' contains a space, which the hidden launcher cannot be handed without " +
    "quoting it and reintroducing the doubled-quote fault. Move the repository to a path without spaces."
}

function Get-LauncherPair($wrapper) {
  if (Test-Path -LiteralPath $HiddenRunner) {
    return "wscript.exe", "`"$HiddenRunner`" `"cmd.exe /c $wrapper`""
  }
  Write-Output "Hidden runner '$HiddenRunner' is absent; cmd.exe will be started directly and its window may flash."
  return "cmd.exe", "/c $wrapper"
}

$launcher, $launcherArguments = Get-LauncherPair $wrapperPath
$innerCommand = "cmd.exe /c $wrapperPath"
$checkoutLabel = if ($Checkout) { $Checkout } else { "$RepoRoot\.local\live-trading-feed-publish" }

# One line per fact, as text: a reader pastes this output into the handoff, and an object dump is not a fact.
function Write-Plan($dictionary) {
  foreach ($key in $dictionary.Keys) {
    $value = $dictionary[$key]
    if ($value -is [bool]) { $value = ([string]$value).ToLower() }
    Write-Output ("{0,-20} = {1}" -f $key, ([string]$value))
  }
}

$plan = [ordered]@{
  task_name            = $TaskName
  interval_minutes     = $IntervalMinutes
  repo_root            = $RepoRoot
  config               = $configPath
  checkout             = $checkoutLabel
  state                = $statePath
  min_interval_seconds = $MinIntervalSeconds
  node                 = $Node
  launcher             = $launcher
  inner_command        = $innerCommand
  wrapper              = $wrapperPath
  writes               = "one commit and one push carrying every lane's artifact, recorded in $statePath"
}

if ($Show) {
  Write-Plan $plan
  return
}

# -Test proves the launcher hop, the lanes file and the publish checkout's credentials - and it proves them with
# --force --dry-run, so a test can never commit or push. It registers a temporary task, runs it the way the real one
# runs, reads the runner's one JSON line out of a log file, then removes the task. A refusal is a real answer here -
# a lane missing, stale, or not the account the lanes file names - so its reason is printed too.
if ($Test) {
  $selfTestName = "$TaskName-SelfTest"
  $selfTestWrapper = Join-Path $RepoRoot "tmp\live-trading-lanes-publish-selftest.cmd"
  Write-Wrapper $selfTestWrapper (Get-WrapperLines "--force --dry-run" $logPath) | Out-Null
  if ($selfTestWrapper -match " ") {
    throw "The self-test wrapper path '$selfTestWrapper' contains a space, which the hidden launcher cannot be " +
      "handed without quoting it and reintroducing the doubled-quote fault."
  }
  $selfTestLauncher, $selfTestArguments = Get-LauncherPair $selfTestWrapper
  $selfTestAction = New-ScheduledTaskAction -Execute $selfTestLauncher -Argument $selfTestArguments
  $selfTestTrigger = New-ScheduledTaskTrigger -Once -At (Get-Date).AddSeconds(10)
  $selfTestSettings = New-ScheduledTaskSettingsSet -MultipleInstances IgnoreNew -StartWhenAvailable `
    -ExecutionTimeLimit (New-TimeSpan -Minutes 5)
  if (Get-ScheduledTask -TaskName $selfTestName -ErrorAction SilentlyContinue) {
    Unregister-ScheduledTask -TaskName $selfTestName -Confirm:$false
  }
  if (Test-Path -LiteralPath $logPath) { Remove-Item -LiteralPath $logPath -Force }
  Register-ScheduledTask -TaskName $selfTestName -Action $selfTestAction -Trigger $selfTestTrigger `
    -Settings $selfTestSettings `
    -Description "Temporary launcher self test for the Live Trading lane publisher. Dry run only." | Out-Null
  Start-ScheduledTask -TaskName $selfTestName

  $lastLine = ""
  $deadline = (Get-Date).AddSeconds(120)
  while ((Get-Date) -lt $deadline) {
    Start-Sleep -Seconds 5
    $info = Get-ScheduledTaskInfo -TaskName $selfTestName
    if ($info.LastTaskResult -ne 267009 -and (Test-Path -LiteralPath $logPath)) {
      $lastLine = (Get-Content -LiteralPath $logPath -Tail 1)
      break
    }
  }
  $taskResult = (Get-ScheduledTaskInfo -TaskName $selfTestName).LastTaskResult
  Unregister-ScheduledTask -TaskName $selfTestName -Confirm:$false

  $action = ""
  if ($lastLine) {
    try { $action = [string](ConvertFrom-Json $lastLine).action } catch { $action = "" }
  }
  $verdict = switch ($action) {
    "would_publish" { "the launcher reached the runner and every gate passed on a dry run; nothing was written or pushed" }
    "unchanged" { "the launcher reached the runner; the branch already carries every lane's snapshot" }
    "too_soon" { "the launcher reached the runner; its interval gate said wait" }
    default {
      if ($lastLine) { "the launcher reached the runner and it refused; the reason is the JSON line below" }
      else { "the launcher never reached the runner" }
    }
  }

  Write-Output "test_task           = $selfTestName (registered, run, removed)"
  Write-Output "test_command        = cmd.exe /c $selfTestWrapper"
  Write-Output "test_dry_run        = yes (--force --dry-run), so a test cannot commit or push"
  Write-Output "test_task_result    = $taskResult"
  Write-Output "test_log            = $logPath"
  Write-Output "test_output         = $lastLine"
  Write-Output "test_verdict        = $verdict"
  return
}

$action = New-ScheduledTaskAction -Execute $launcher -Argument $launcherArguments
# An interval with no duration is an indefinite repetition on this engine, the same shape the feed cadence runs.
$trigger = New-ScheduledTaskTrigger -Once -At (Get-Date).AddSeconds(30) `
  -RepetitionInterval (New-TimeSpan -Minutes $IntervalMinutes)
# StartWhenAvailable picks the cadence back up after a reboot; IgnoreNew keeps a run that is still pushing and the
# next repetition from racing the same checkout. The fifteen-minute limit covers the fetch, commit and push.
$settings = New-ScheduledTaskSettingsSet -StartWhenAvailable -MultipleInstances IgnoreNew `
  -AllowStartIfOnBatteries -DontStopIfGoingOnBatteries `
  -ExecutionTimeLimit (New-TimeSpan -Minutes 15)
$description = "Publishes every Live Trading lane's validated snapshot to the branch Pages serves, in one commit, " +
  "at most once every $MinIntervalSeconds seconds, through scripts/publish-live-trading-lanes.js. Refuses rather " +
  "than warns on a missing, stale or wrongly-attributed lane."

# Replace any earlier registration cleanly: -Force over a task whose run is still in flight left the scheduler
# reporting it as running and refusing every repetition (observed 2026-10-04).
$existing = Get-ScheduledTask -TaskName $TaskName -ErrorAction SilentlyContinue
if ($existing) {
  if ($existing.State -eq "Running") { Stop-ScheduledTask -TaskName $TaskName }
  Unregister-ScheduledTask -TaskName $TaskName -Confirm:$false
}

Register-ScheduledTask -TaskName $TaskName -Action $action -Trigger $trigger -Settings $settings `
  -Description $description | Out-Null

$task = Get-ScheduledTask -TaskName $TaskName
$plan["task_state"] = $task.State
$plan["registered_at"] = (Get-Date).ToString("o")

if (-not $NoStart) {
  Start-ScheduledTask -TaskName $TaskName
  Start-Sleep -Seconds 8
  $info = Get-ScheduledTaskInfo -TaskName $TaskName
  $plan["last_run_time"] = $info.LastRunTime.ToString("o")
  $plan["last_task_result"] = $info.LastTaskResult
  $plan["next_run_time"] = $info.NextRunTime.ToString("o")
  $plan["task_result_note"] = "0 = published or nothing to publish; 1 = a gate refused or git failed (the reason is in the task history)"
}

Write-Plan $plan

